import type { AccountSubtype, AccountType } from '@nexera/shared';

export interface TemplateAccount {
  code: string;
  en: string;
  ar: string;
  type: AccountType;
  subtype: AccountSubtype;
  // The code of the header this account sits under.
  parent?: string;
  // Headers only group other accounts.
  header?: boolean;
  concept?: string;
}

const h = (
  code: string,
  en: string,
  ar: string,
  type: AccountType,
  subtype: AccountSubtype,
  parent?: string,
): TemplateAccount => ({
  code,
  en,
  ar,
  type,
  subtype,
  header: true,
  ...(parent ? { parent } : {}),
});

const a = (
  code: string,
  en: string,
  ar: string,
  type: AccountType,
  subtype: AccountSubtype,
  parent: string,
  concept: string,
): TemplateAccount => ({ code, en, ar, type, subtype, parent, concept: `ifrs-full:${concept}` });

